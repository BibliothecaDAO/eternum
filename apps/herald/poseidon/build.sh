#!/usr/bin/env bash
# Rebuilds Herald's Poseidon WebAssembly and embeds it in src/native/poseidon-wasm.gen.ts, the file Herald imports.
# Herald ships as one bundled herald.js, so the module travels as base64 inside it rather than as a .wasm beside it.
set -euo pipefail
cd "$(dirname "$0")"
cargo build --release --locked --target wasm32-unknown-unknown
wasm=target/wasm32-unknown-unknown/release/herald_poseidon.wasm
{
  echo "// Generated by apps/herald/poseidon/build.sh from apps/herald/poseidon/src/lib.rs; do not edit."
  echo "// herald_poseidon.wasm sha256 $(sha256sum "$wasm" | cut -d' ' -f1), $(stat -c %s "$wasm") bytes."
  printf 'export const POSEIDON_WASM_BASE64 =\n  "%s";\n' "$(base64 -w0 "$wasm")"
} > ../src/native/poseidon-wasm.gen.ts
