import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { hash } from "starknet";

const registryPath = new URL("../../packages/settlement-codec/schema/schema-registry-v1.json", import.meta.url);
const jsonOutput = new URL("../../packages/settlement-codec/schema/tree-vectors-v1.json", import.meta.url);
const cairoOutput = new URL("../../contracts/settlement_protocol/src/tree_vectors.cairo", import.meta.url);
const rustOutput = new URL("../../proofs/eternum-settlement/src/tree_vectors.rs", import.meta.url);
const shouldCheck = process.argv.includes("--check");
const registry = JSON.parse(readFileSync(registryPath, "utf8"));
const vectors = buildTreeVectors(registry);

writeGenerated(jsonOutput, `${JSON.stringify(vectors, null, 2)}\n`);
writeGenerated(cairoOutput, renderCairo(vectors));
writeGenerated(rustOutput, renderRust(vectors));

function buildTreeVectors(sourceRegistry) {
  const claimTree = requireTree(sourceRegistry, "claim");
  const refundTree = requireTree(sourceRegistry, "deployment-refund-source");
  const rankingTree = requireTree(sourceRegistry, "ranking");
  const mmrPlanTree = requireTree(sourceRegistry, "mmr-plan");
  return {
    protocolVersion: sourceRegistry.protocolVersion,
    cases: [
      buildCase("one", claimTree, 1, 1),
      buildCase("two", claimTree, 1, 2),
      buildCase("partial", claimTree, 1, 17),
      buildCase("sixty-three", claimTree, 1, 63),
      buildCase("full", claimTree, 1, 64),
      buildCase("consecutive-full", claimTree, 65, 64),
      buildCase("final", claimTree, 129, 5),
      buildCase("refund-source-one", refundTree, 1, 1),
      buildCase("ranking-three", rankingTree, 1, 3),
      buildCase("mmr-plan-three", mmrPlanTree, 1, 3),
    ],
  };
}

function requireTree(sourceRegistry, name) {
  const tree = sourceRegistry.trees.find((candidate) => candidate.name === name);
  if (!tree) throw new Error(`missing tree registry entry: ${name}`);
  return tree;
}

function buildCase(name, tree, firstValue, count) {
  const leafDomain = hash.getSelectorFromName(tree.leafDomain);
  const leafHashes = Array.from({ length: count }, (_, index) => poseidon([leafDomain, firstValue + index]));
  const built = buildTree(tree, leafHashes);
  const proofIndices = [...new Set([0, count - 1])];
  return {
    name,
    tree: tree.name,
    depth: tree.depth,
    firstValue,
    leafHashes,
    root: built.root,
    proofs: proofIndices.map((index) => ({ index, siblings: buildProof(built, index) })),
  };
}

function buildTree(tree, leafHashes) {
  if (leafHashes.length > tree.capacity) throw new Error(`tree capacity exceeded: ${tree.name}`);
  const emptyNodes = buildEmptyNodes(tree);
  const levels = [new Map(leafHashes.map((leaf, index) => [index, leaf]))];
  const nodeDomain = hash.getSelectorFromName(tree.nodeDomain);
  for (let depth = 0; depth < tree.depth; depth += 1) {
    const previous = levels[depth];
    const parentIndices = new Set([...previous.keys()].map((index) => Math.floor(index / 2)));
    levels.push(
      new Map(
        [...parentIndices].map((index) => [
          index,
          poseidon([
            nodeDomain,
            previous.get(index * 2) ?? emptyNodes[depth],
            previous.get(index * 2 + 1) ?? emptyNodes[depth],
          ]),
        ]),
      ),
    );
  }
  return { emptyNodes, levels, root: levels.at(-1).get(0) ?? emptyNodes[tree.depth] };
}

function buildEmptyNodes(tree) {
  const nodes = [poseidon([hash.getSelectorFromName(tree.emptyLeafDomain)])];
  const nodeDomain = hash.getSelectorFromName(tree.nodeDomain);
  for (let depth = 0; depth < tree.depth; depth += 1) {
    nodes.push(poseidon([nodeDomain, nodes[depth], nodes[depth]]));
  }
  return nodes;
}

function buildProof({ emptyNodes, levels }, leafIndex) {
  let index = leafIndex;
  return levels.slice(0, -1).map((level, depth) => {
    const sibling = level.get(index ^ 1) ?? emptyNodes[depth];
    index = Math.floor(index / 2);
    return sibling;
  });
}

function poseidon(values) {
  return hash.computePoseidonHashOnElements(values.map(String));
}

function renderCairo({ cases }) {
  return `// Generated by scripts/settlement/generate-tree-vectors.mjs. Do not edit directly.
pub fn tree_vectors() -> Array<(felt252, u8, felt252, felt252, Array<felt252>)> {
    array![
${cases
  .map(
    (vector) =>
      `        ('${vector.name}', ${vector.depth}, ${hash.getSelectorFromName(requireTree(registry, vector.tree).emptyLeafDomain)}, ${hash.getSelectorFromName(requireTree(registry, vector.tree).nodeDomain)}, array![${vector.leafHashes.join(", ")}]),`,
  )
  .join("\n")}
    ]
}

pub fn expected_roots() -> Array<felt252> {
    array![${cases.map(({ root }) => root).join(", ")}]
}

pub fn proof_vectors() -> Array<(felt252, u8, felt252, usize, felt252, felt252, Array<felt252>)> {
    array![
${cases
  .flatMap((vector) => {
    const tree = requireTree(registry, vector.tree);
    return vector.proofs.map(
      (proof) =>
        `        ('${vector.name}', ${vector.depth}, ${hash.getSelectorFromName(tree.nodeDomain)}, ${proof.index}, ${vector.leafHashes[proof.index]}, ${vector.root}, array![${proof.siblings.join(", ")}]),`,
    );
  })
  .join("\n")}
    ]
}
`;
}

function renderRust({ cases }) {
  return `// Generated by scripts/settlement/generate-tree-vectors.mjs. Do not edit directly.
pub struct TreeVector {
    pub name: &'static str,
    pub depth: u8,
    pub empty_leaf_domain: &'static str,
    pub node_domain: &'static str,
    pub leaf_hashes: &'static [&'static str],
    pub root: &'static str,
    pub proofs: &'static [(usize, &'static [&'static str])],
}

pub const TREE_VECTORS: &[TreeVector] = &[
${cases
  .map((vector) => {
    const tree = requireTree(registry, vector.tree);
    return `    TreeVector { name: "${vector.name}", depth: ${vector.depth}, empty_leaf_domain: "${hash.getSelectorFromName(tree.emptyLeafDomain)}", node_domain: "${hash.getSelectorFromName(tree.nodeDomain)}", leaf_hashes: &[${vector.leafHashes.map((leaf) => `"${leaf}"`).join(", ")}], root: "${vector.root}", proofs: &[${vector.proofs.map((proof) => `(${proof.index}, &[${proof.siblings.map((sibling) => `"${sibling}"`).join(", ")}])`).join(", ")}] },`;
  })
  .join("\n")}
];
`;
}

function writeGenerated(output, content) {
  if (!shouldCheck) {
    writeFileSync(output, content);
    return;
  }
  const current = readFileSync(output, "utf8");
  if (normalize(output, current) !== normalize(output, content)) {
    throw new Error(`stale generated tree artifact: ${output.pathname}`);
  }
}

function normalize(output, content) {
  if (output.pathname.endsWith(".json")) return JSON.stringify(JSON.parse(content));
  if (output.pathname.endsWith(".rs")) {
    return execFileSync("rustfmt", ["--emit", "stdout", "--edition", "2024"], {
      encoding: "utf8",
      input: content,
    });
  }
  return content.replaceAll(/\s+/g, "").replaceAll(/,([\]\)}])/g, "$1");
}
