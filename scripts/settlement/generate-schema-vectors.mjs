function renderCairoUseGroup(path, names) {
  const lines = [];
  for (const name of names.toSorted()) {
    const suffix = `${name},`;
    if (lines.length === 0) {
      lines.push(`    ${suffix}`);
      continue;
    }
    const candidate = `${lines.at(-1)} ${suffix}`;
    if (candidate.length <= 120) {
      lines[lines.length - 1] = candidate;
    } else {
      lines.push(`    ${suffix}`);
    }
  }
  return `use ${path}::{\n${lines.join("\n")}\n};`;
}

function buildGoldenVectors({ declarations, schemaRegistryHash, trees }) {
  const declarationsByName = new Map(declarations.map((declaration) => [declaration.name, declaration]));
  const schemas = declarations
    .filter(({ kind }) => kind === "struct")
    .map((declaration) => {
      const counter = { value: 1n };
      const fixture = buildFixture(declaration.name, declarationsByName, counter);
      return { schema: declaration.name, value: fixture.value, felts: fixture.felts };
    });

  return {
    protocolVersion: 1,
    schemaRegistryHash,
    schemas,
    u256: {
      value: ((1n << 128n) + 5n).toString(),
      felts: ["5", "1"],
    },
    trees: trees.map(buildEmptyTreeVector),
  };
}

function buildFixture(type, declarationsByName, counter) {
  const normalizedType = type.trim();
  if (normalizedType === "bool") {
    const value = counter.value++ % 2n === 1n;
    return { value, felts: [value ? "1" : "0"] };
  }
  if (normalizedType === "u256") {
    const low = counter.value++;
    const high = counter.value++;
    return { value: (low + (high << 128n)).toString(), felts: [low.toString(), high.toString()] };
  }
  if (isFeltType(normalizedType)) {
    const value = counter.value++;
    return { value: value.toString(), felts: [value.toString()] };
  }
  if (isVectorType(normalizedType)) {
    const itemType = normalizedType.slice(normalizedType.indexOf("<") + 1, -1);
    const item = buildFixture(itemType, declarationsByName, counter);
    return { value: [item.value], felts: ["1", ...item.felts] };
  }
  if (normalizedType.startsWith("(") && normalizedType.endsWith(")")) {
    return combineFixtures(
      splitTypes(normalizedType.slice(1, -1)).map((itemType) => buildFixture(itemType, declarationsByName, counter)),
      (fixtures) => fixtures.map(({ value }) => value),
    );
  }

  const declaration = declarationsByName.get(normalizedType);
  if (!declaration) throw new Error(`undeclared ABI type: ${normalizedType}`);
  if (declaration.kind === "type") return buildFixture(declaration.alias, declarationsByName, counter);
  if (declaration.kind === "struct") {
    return combineFixtures(
      declaration.members.map((member) => buildFixture(member.type, declarationsByName, counter)),
      (fixtures) => Object.fromEntries(fixtures.map(({ value }, index) => [declaration.members[index].name, value])),
    );
  }
  if (declaration.kind === "enum") {
    const variantIndex = Number(counter.value++ % BigInt(declaration.members.length));
    const variant = declaration.members[variantIndex];
    if (!variant.type) {
      return { value: { variant: variant.name }, felts: [variantIndex.toString()] };
    }
    const payload = buildFixture(variant.type, declarationsByName, counter);
    return {
      value: { variant: variant.name, value: payload.value },
      felts: [variantIndex.toString(), ...payload.felts],
    };
  }
  throw new Error(`interfaces are not serializable: ${normalizedType}`);
}

function combineFixtures(fixtures, buildValue) {
  return {
    value: buildValue(fixtures),
    felts: fixtures.flatMap(({ felts }) => felts),
  };
}

function isFeltType(type) {
  return /^(felt252|ContractAddress|u8|u16|u32|u64|u128)$/.test(type);
}

function isVectorType(type) {
  return /^(Span|Array)<.+>$/.test(type);
}

function buildEmptyTreeVector(tree) {
  const emptyNodes = [hash.computePoseidonHashOnElements([hash.getSelectorFromName(tree.emptyLeafDomain)])];
  const nodeDomain = hash.getSelectorFromName(tree.nodeDomain);
  for (let depth = 0; depth < tree.depth; depth += 1) {
    emptyNodes.push(hash.computePoseidonHashOnElements([nodeDomain, emptyNodes[depth], emptyNodes[depth]]));
  }
  return { ...tree, emptyNodes };
}

