function writeGenerated(output, content) {
  if (!shouldCheck) {
    writeFileSync(output, content);
    return;
  }
  const current = readFileSync(output, "utf8");
  const normalizedCurrent = normalizeGenerated(output, current);
  const normalizedGenerated = normalizeGenerated(output, content);
  if (normalizedCurrent !== normalizedGenerated) {
    const mismatch = firstMismatch(normalizedCurrent, normalizedGenerated);
    const currentContext = normalizedCurrent.slice(mismatch, mismatch + 80);
    const generatedContext = normalizedGenerated.slice(mismatch, mismatch + 80);
    throw new Error(
      `stale generated settlement artifact at normalized offset ${mismatch}: ${output.pathname}\ncurrent: ${JSON.stringify(currentContext)}\ngenerated: ${JSON.stringify(generatedContext)}`,
    );
  }
}

function firstMismatch(left, right) {
  const sharedLength = Math.min(left.length, right.length);
  for (let index = 0; index < sharedLength; index += 1) {
    if (left[index] !== right[index]) return index;
  }
  return sharedLength;
}

function normalizeGenerated(output, content) {
  if (output.pathname.endsWith(".json")) return JSON.stringify(JSON.parse(content));
  const literalQuotes = output.pathname.endsWith(".rs") ? new Set(['"']) : new Set(['"', "'"]);
  return removeWhitespaceOutsideLiterals(content, literalQuotes)
    .replaceAll(/=>\{(Some\([^{}]+\))\}/g, "=>$1,")
    .replaceAll(/,([\]\)}>])/g, "$1")
    .replaceAll(/},(?=Self::)/g, "}");
}

function removeWhitespaceOutsideLiterals(content, literalQuotes) {
  let normalized = "";
  let quote = null;
  let escaped = false;
  for (const character of content) {
    if (quote) {
      normalized += character;
      if (escaped) escaped = false;
      else if (character === "\\") escaped = true;
      else if (character === quote) quote = null;
      continue;
    }
    if (literalQuotes.has(character)) {
      quote = character;
      normalized += character;
    } else if (!/\s/.test(character)) {
      normalized += character;
    }
  }
  if (quote) throw new Error("generated settlement source contains an unterminated literal");
  return normalized;
}

