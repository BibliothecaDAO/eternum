function renderRustFixture(type, value, declarationsByName) {
  const normalizedType = type.trim();
  if (normalizedType === "bool") return value.toString();
  if (normalizedType === "u256") {
    const integer = BigInt(value);
    const mask = (1n << 128n) - 1n;
    return `U256 { low: ${integer & mask}_u128, high: ${integer >> 128n}_u128 }`;
  }
  if (normalizedType === "felt252" || normalizedType === "ContractAddress") return `felt("${value}")`;
  if (/^u(8|16|32|64|128)$/.test(normalizedType)) return `${value}_${normalizedType}`;
  if (isVectorType(normalizedType)) {
    const itemType = normalizedType.slice(normalizedType.indexOf("<") + 1, -1);
    return `vec![${value.map((item) => renderRustFixture(itemType, item, declarationsByName)).join(", ")}]`;
  }
  if (normalizedType.startsWith("(") && normalizedType.endsWith(")")) {
    const itemTypes = splitTypes(normalizedType.slice(1, -1));
    return `(${itemTypes.map((itemType, index) => renderRustFixture(itemType, value[index], declarationsByName)).join(", ")})`;
  }

  const declaration = declarationsByName.get(normalizedType);
  if (!declaration) throw new Error(`undeclared ABI type: ${normalizedType}`);
  if (declaration.kind === "type") return renderRustFixture(declaration.alias, value, declarationsByName);
  if (declaration.kind === "struct") {
    return `${declaration.name} { ${declaration.members
      .map((member) => `${member.name}: ${renderRustFixture(member.type, value[member.name], declarationsByName)}`)
      .join(", ")} }`;
  }
  if (declaration.kind === "enum") {
    const variant = declaration.members.find((member) => member.name === value.variant);
    if (!variant) throw new Error(`unknown fixture variant: ${declaration.name}.${value.variant}`);
    const payload = variant.type ? `(${renderRustFixture(variant.type, value.value, declarationsByName)})` : "";
    return `${declaration.name}::${variant.name}${payload}`;
  }
  throw new Error(`interfaces are not serializable: ${normalizedType}`);
}

function toSnakeCase(value) {
  return value.replace(/([a-z0-9])([A-Z])/g, "$1_$2").toLowerCase();
}

function validateRegistry({ declarations, indexFamilies }) {
  const familyCodes = indexFamilies.map(({ code }) => code);
  const familyNames = indexFamilies.map(({ name }) => name);
  if (new Set(familyCodes).size !== familyCodes.length || new Set(familyNames).size !== familyNames.length) {
    throw new Error("index family codes and names must be unique");
  }
  const worldCodes = indexFamilies.filter(({ scope }) => scope === "world").map(({ code }) => code);
  if (JSON.stringify(worldCodes) !== JSON.stringify(Array.from({ length: 12 }, (_, index) => index + 1))) {
    throw new Error("World index families must remain contiguous and one-based");
  }
  const deploymentFamily = indexFamilies.find(({ name }) => name === "DEPLOYMENT_REFUND_SOURCE");
  if (deploymentFamily?.code !== 65_535 || deploymentFamily.scope !== "deployment") {
    throw new Error("DEPLOYMENT_REFUND_SOURCE must remain the deployment-scoped u16::MAX family");
  }
  const declarationNames = new Set(declarations.map(({ name }) => name));
  const allowedTypes = new Set(["Array", "ByteArray", "ContractAddress", "Option", "Span", "TContractState"]);
  for (const declaration of declarations) {
    const typeSources =
      declaration.kind === "trait"
        ? declaration.members
        : [declaration.alias, ...(declaration.members ?? []).map(({ type }) => type)].filter(Boolean);
    for (const source of typeSources) {
      for (const typeName of source.match(/\b[A-Z][A-Za-z0-9_]*\b/g) ?? []) {
        if (!declarationNames.has(typeName) && !allowedTypes.has(typeName)) {
          throw new Error(`undeclared ABI type: ${declaration.name} references ${typeName}`);
        }
      }
    }
  }
}

function assertUndeclaredAbiTypeRejected(sourceRegistry) {
  const candidate = structuredClone(sourceRegistry);
  candidate.declarations
    .find(({ kind }) => kind === "struct")
    .members.push({
      name: "undeclared_type_probe",
      type: "UndeclaredSettlementAbiType",
    });
  try {
    validateRegistry(candidate);
  } catch (error) {
    if (error instanceof Error && error.message.includes("undeclared ABI type")) return;
    throw error;
  }
  throw new Error("undeclared ABI type validation is not active");
}

function renderRustCodec({ declarations }) {
  const dataDeclarations = declarations.filter(({ kind }) => kind === "struct" || kind === "enum");
  return `// Generated by scripts/settlement/generate-schema-vectors.mjs. Do not edit directly.
use starknet_crypto::Felt;

use crate::types::*;

pub trait CanonicalEncode {
    fn encode_to(&self, output: &mut Vec<Felt>);

    fn encode(&self) -> Vec<Felt> {
        let mut output = Vec::new();
        self.encode_to(&mut output);
        output
    }
}

macro_rules! encode_unsigned {
    ($($type:ty),+ $(,)?) => {
        $(
            impl CanonicalEncode for $type {
                fn encode_to(&self, output: &mut Vec<Felt>) {
                    output.push(Felt::from(*self));
                }
            }
        )+
    };
}

encode_unsigned!(u8, u16, u32, u64, u128);

impl CanonicalEncode for Felt {
    fn encode_to(&self, output: &mut Vec<Felt>) {
        output.push(*self);
    }
}

impl CanonicalEncode for bool {
    fn encode_to(&self, output: &mut Vec<Felt>) {
        output.push(Felt::from(u8::from(*self)));
    }
}

impl CanonicalEncode for U256 {
    fn encode_to(&self, output: &mut Vec<Felt>) {
        output.push(Felt::from(self.low));
        output.push(Felt::from(self.high));
    }
}

impl<T: CanonicalEncode> CanonicalEncode for Vec<T> {
    fn encode_to(&self, output: &mut Vec<Felt>) {
        output.push(Felt::from(self.len() as u64));
        for value in self {
            value.encode_to(output);
        }
    }
}

${[2, 3, 4, 5].map(renderTupleEncoder).join("\n\n")}

${dataDeclarations.map(renderRustEncoder).join("\n\n")}
`;
}

function renderTupleEncoder(arity) {
  const typeNames = Array.from({ length: arity }, (_, index) => String.fromCharCode(65 + index));
  const indexes = Array.from({ length: arity }, (_, index) => index);
  return `impl<${typeNames.map((name) => `${name}: CanonicalEncode`).join(", ")}> CanonicalEncode for (${typeNames.join(", ")}) {
    fn encode_to(&self, output: &mut Vec<Felt>) {
${indexes.map((index) => `        self.${index}.encode_to(output);`).join("\n")}
    }
}`;
}

function renderRustEncoder(declaration) {
  if (declaration.kind === "struct") {
    return `impl CanonicalEncode for ${declaration.name} {
    fn encode_to(&self, output: &mut Vec<Felt>) {
${declaration.members.map((member) => `        self.${member.name}.encode_to(output);`).join("\n")}
    }
}`;
  }

  const variants = declaration.members
    .map((member, index) => {
      if (!member.type) {
        return `            Self::${member.name} => ${index}u8.encode_to(output),`;
      }
      return `            Self::${member.name}(value) => {
                ${index}u8.encode_to(output);
                value.encode_to(output);
            },`;
    })
    .join("\n");
  return `impl CanonicalEncode for ${declaration.name} {
    fn encode_to(&self, output: &mut Vec<Felt>) {
        match self {
${variants}
        }
    }
}`;
}
