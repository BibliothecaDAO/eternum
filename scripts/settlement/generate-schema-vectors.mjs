function renderRustDeclaration(declaration) {
  if (declaration.kind === "type") {
    return `pub type ${declaration.name} = ${rustType(declaration.alias)};`;
  }
  if (declaration.kind === "struct") {
    const fields = declaration.members.map((member) => `    pub ${member.name}: ${rustType(member.type)},`).join("\n");
    return `#[derive(Debug, Clone, PartialEq, Eq)]\npub struct ${declaration.name} {\n${fields}\n}`;
  }
  const variants = declaration.members
    .map((member) => `    ${member.name}${member.type ? `(${rustType(member.type)})` : ""},`)
    .join("\n");
  return `#[allow(clippy::large_enum_variant)]\n#[derive(Debug, Clone, PartialEq, Eq)]\npub enum ${declaration.name} {\n${variants}\n}`;
}

function rustType(type) {
  return type
    .replaceAll("felt252", "Felt")
    .replaceAll("ContractAddress", "Felt")
    .replaceAll("u256", "U256")
    .replaceAll("Span<", "Vec<")
    .replaceAll("Array<", "Vec<");
}

