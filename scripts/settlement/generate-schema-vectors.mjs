function renderTypescriptDeclaration(declaration) {
  if (declaration.kind === "type") {
    return `export type ${declaration.name} = ${typescriptType(declaration.alias)};`;
  }
  if (declaration.kind === "struct") {
    const fields = declaration.members
      .map((member) => `  readonly ${member.name}: ${typescriptType(member.type)};`)
      .join("\n");
    return `export interface ${declaration.name} {\n${fields}\n}`;
  }
  const variants = declaration.members
    .map((member) =>
      member.type
        ? `{ readonly variant: "${member.name}"; readonly value: ${typescriptType(member.type)} }`
        : `{ readonly variant: "${member.name}" }`,
    )
    .join("\n  | ");
  return `export type ${declaration.name} =\n  | ${variants};`;
}

function typescriptType(type) {
  if (type === "bool") return "boolean";
  if (/^(felt252|ContractAddress|u8|u16|u32|u64|u128|u256)$/.test(type)) return "bigint";
  if (/^(Span|Array)<.+>$/.test(type)) return `readonly ${typescriptType(type.slice(type.indexOf("<") + 1, -1))}[]`;
  if (type.startsWith("(") && type.endsWith(")")) {
    return `readonly [${splitTypes(type.slice(1, -1)).map(typescriptType).join(", ")}]`;
  }
  return type;
}

function splitTypes(types) {
  const result = [];
  let depth = 0;
  let start = 0;
  for (let index = 0; index < types.length; index += 1) {
    if (types[index] === "<" || types[index] === "(") depth += 1;
    if (types[index] === ">" || types[index] === ")") depth -= 1;
    if (types[index] === "," && depth === 0) {
      result.push(types.slice(start, index).trim());
      start = index + 1;
    }
  }
  result.push(types.slice(start).trim());
  return result;
}

