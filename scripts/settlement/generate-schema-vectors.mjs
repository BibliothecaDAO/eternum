function renderCairoDeclaration(declaration) {
  if (declaration.kind === "type") {
    return `pub type ${declaration.name} = ${declaration.alias};`;
  }

  const members = declaration.members
    .map((member) => {
      const type = member.type ? `: ${member.type}` : "";
      const visibility = declaration.kind === "struct" ? "pub " : "";
      return `    ${visibility}${member.name}${type},`;
    })
    .join("\n");
  return `#[derive(Drop, Serde)]\npub ${declaration.kind} ${declaration.name} {\n${members}\n}`;
}

