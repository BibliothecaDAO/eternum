import { readFileSync, writeFileSync } from "node:fs";
import { relative, resolve } from "node:path";
import { hash } from "starknet";

const repositoryRoot = resolve(import.meta.dirname, "../..");
const jsonOutputPath = resolve(repositoryRoot, "packages/settlement-codec/schema/config-setter-inventory-v0.json");
const cairoOutputPath = resolve(repositoryRoot, "contracts/settlement_protocol/src/config_setter_vectors.cairo");
const shouldCheck = process.argv.includes("--check");

const surfaces = [
  {
    scope: "world",
    interfacePath: "contracts/game/src/systems/config/contracts.cairo",
    implementationPath: "contracts/game/src/systems/config/contracts.cairo",
  },
  {
    scope: "factory",
    interfacePath: "contracts/factory/src/interface.cairo",
    implementationPath: "contracts/factory/src/factory.cairo",
  },
];

const entries = surfaces.flatMap(inventorySurface).sort(compareEntries);
const inventory = {
  version: 0,
  status: "a11-feasibility-inventory",
  summary: summarize(entries),
  entries,
};

writeOrCheck(jsonOutputPath, `${JSON.stringify(inventory, null, 2)}\n`);
writeOrCheck(cairoOutputPath, renderCairoVectors(entries));

function inventorySurface(surface) {
  const interfaceSource = readRepositoryFile(surface.interfacePath);
  const implementationSource = readRepositoryFile(surface.implementationPath);
  return extractInterfaceTraits(interfaceSource).flatMap(({ trait, body, bodyOffset }) =>
    extractSetters(body).map(({ name, signature, offset }) => {
      const interfaceLine = lineNumberAt(interfaceSource, bodyOffset + offset);
      const implementationLines = findFunctionLines(implementationSource, name).filter(
        (line) => surface.interfacePath !== surface.implementationPath || line !== interfaceLine,
      );
      return {
        scope: surface.scope,
        trait,
        name,
        selector: hash.getSelectorFromName(name),
        signature,
        interfacePath: surface.interfacePath,
        interfaceLine,
        implementationPath: surface.implementationPath,
        implementationLine: implementationLines.at(-1) ?? null,
        implementationStatus: implementationLines.length > 0 ? "implemented" : "missing",
      };
    }),
  );
}

function extractInterfaceTraits(source) {
  const traits = [];
  const traitPattern = /#\[starknet::interface\]\s*pub trait\s+([A-Za-z0-9_]+)<[^>]+>\s*{/g;
  for (const match of source.matchAll(traitPattern)) {
    const openingBrace = match.index + match[0].lastIndexOf("{");
    const closingBrace = findClosingBrace(source, openingBrace);
    traits.push({ trait: match[1], body: source.slice(openingBrace + 1, closingBrace), bodyOffset: openingBrace + 1 });
  }
  return traits;
}

function extractSetters(body) {
  const setters = [];
  const methodPattern = /fn\s+(set_[A-Za-z0-9_]+)\s*\(([\s\S]*?)\)\s*(?:->\s*[^;]+)?;/g;
  for (const match of body.matchAll(methodPattern)) {
    setters.push({
      name: match[1],
      signature: `fn ${match[1]}(${normalizeWhitespace(match[2])})`,
      offset: match.index,
    });
  }
  return setters;
}

function findClosingBrace(source, openingBrace) {
  let depth = 0;
  for (let index = openingBrace; index < source.length; index += 1) {
    if (source[index] === "{") depth += 1;
    if (source[index] === "}") depth -= 1;
    if (depth === 0) return index;
  }
  throw new Error(`unclosed interface trait at byte ${openingBrace}`);
}

function findFunctionLines(source, name) {
  const lines = [];
  const pattern = new RegExp(`\\bfn\\s+${name}\\s*\\(`, "g");
  for (const match of source.matchAll(pattern)) lines.push(lineNumberAt(source, match.index));
  return lines;
}

function lineNumberAt(source, offset) {
  return source.slice(0, offset).split("\n").length;
}

function normalizeWhitespace(value) {
  return value.replace(/\s+/g, " ").trim();
}

function compareEntries(left, right) {
  return left.scope.localeCompare(right.scope) || left.name.localeCompare(right.name);
}

function summarize(allEntries) {
  return {
    total: allEntries.length,
    world: allEntries.filter((entry) => entry.scope === "world").length,
    factory: allEntries.filter((entry) => entry.scope === "factory").length,
    implemented: allEntries.filter((entry) => entry.implementationStatus === "implemented").length,
    missingImplementation: allEntries.filter((entry) => entry.implementationStatus === "missing").length,
  };
}

function renderCairoVectors(allEntries) {
  const lines = [
    "// Generated by scripts/settlement/generate-config-setter-inventory.mjs. Do not edit directly.",
    `pub const CONFIG_SETTER_COUNT: usize = ${allEntries.length};`,
    "",
    "pub fn config_setter_selectors() -> Array<felt252> {",
    "    array![",
  ];
  for (const [index, entry] of allEntries.entries()) {
    const comma = index + 1 === allEntries.length ? "" : ",";
    lines.push(`        ${entry.selector}${comma} // ${entry.scope}:${entry.name}`);
  }
  lines.push("    ]", "}", "");
  return lines.join("\n");
}

function readRepositoryFile(path) {
  return readFileSync(resolve(repositoryRoot, path), "utf8");
}

function writeOrCheck(path, rendered) {
  if (shouldCheck) {
    const current = readFileSync(path, "utf8");
    if (current !== rendered)
      throw new Error(`stale generated config setter artifact: ${relative(repositoryRoot, path)}`);
    return;
  }
  writeFileSync(path, rendered);
}
