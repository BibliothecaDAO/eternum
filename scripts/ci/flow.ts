import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { root, validationJobs, type ValidationJob } from "./jobs";

const marker = "# Validation jobs generated by bun scripts/ci/flow.ts --write\n";
export const kindName = (job: ValidationJob) => `ci-${job.id.replaceAll("/", "-")}`;

export function validationPaths(): Record<string, string[]> {
  const result = Bun.spawnSync(["python3", ".github/scripts/validation_areas.py", "--flow-paths"], { cwd: root });
  if (result.exitCode !== 0) throw new Error(result.stderr.toString());
  return JSON.parse(result.stdout.toString());
}

/** Run commands stay in their workflow. Only scheduling inputs are materialized for flow. */
function definitions(jobs: ValidationJob[], paths: Record<string, string[]>): string {
  return jobs
    .map((job) => {
      const areaPaths = job.area === "static" ? [] : paths[job.area];
      if (!areaPaths) throw new Error(`No validation paths for ${job.area}`);
      return `[kind.${kindName(job)}]\ncmd = "bun scripts/ci/run.ts ${job.id}"\n${areaPaths.length ? `paths = "${areaPaths.join(" ")}"\n` : ""}`;
    })
    .join("\n");
}

export const FLOW_DRIFT =
  "flow.toml differs from what bun scripts/ci/flow.ts --write writes: run it, and keep hand-written kinds above its marker";

export function parityProblems(source: string, jobs = validationJobs(), paths = validationPaths()): string[] {
  return writeFlow(source, jobs, paths) === source ? [] : [FLOW_DRIFT];
}

function writeFlow(source: string, jobs: ValidationJob[], paths: Record<string, string[]>): string {
  const base = source.split(marker)[0]!.trimEnd();
  const rewritten = base.replace(
    /(\[land\]\nkinds = ")([^"]+)(")/,
    (_, start, listed, end) =>
      start +
      [...listed.split(/\s+/).filter((kind: string) => !kind.startsWith("ci-")), ...jobs.map(kindName)].join(" ") +
      end,
  );
  return `${rewritten}\n\n${marker}${definitions(jobs, paths)}`;
}

if (import.meta.main) {
  const path = resolve(root, "flow.toml");
  const source = readFileSync(path, "utf8");
  if (process.argv[2] === "--write") writeFileSync(path, writeFlow(source, validationJobs(), validationPaths()));
  else {
    const problems = parityProblems(source);
    if (problems.length) throw new Error(problems.join("\n"));
    console.log(`${validationJobs().length} validation jobs have matching landing kinds, commands and paths`);
  }
}
