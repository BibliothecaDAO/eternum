import assert from "node:assert/strict";
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import test from "node:test";
import { BLITZ_MARKS, checkBlitzMarks, countBlitzMarks, worldSource } from "./check-blitz-marks.mjs";

function withMarkedTree(run) {
  const dir = mkdtempSync(join(tmpdir(), "blitz-marks-"));
  try {
    const marks = '#[cfg(feature: "blitz")]\nfn one() {}\n#[cfg(not(feature:"blitz"))]\nfn two() {}\n';
    mkdirSync(join(dir, "logic"));
    writeFileSync(join(dir, "logic", "marked.cairo"), marks);
    writeFileSync(join(dir, "notes.md"), marks);
    writeFileSync(join(dir, "copy.ts"), marks);
    writeFileSync(join(dir, "swap.cairo"), `// @generated by a module writer. DO NOT EDIT.\n${marks}`);
    run(dir);
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

test("only marks in hand-written Cairo files count, one per match", () => {
  withMarkedTree((dir) => assert.equal(countBlitzMarks(dir), 2));
});

test("a mark above the figure is refused", () => {
  withMarkedTree((dir) =>
    assert.equal(
      checkBlitzMarks(dir, 1),
      "contracts/l3/world-native/src has 2 Blitz marks, the most allowed is 1: put Blitz code in a Blitz file picked by the Blitz build (logic/blitz/, balance/blitz/, the way balance.cairo swaps its modules), not as a mark in a Frontier file",
    ),
  );
});

test("a mark removed lowers the figure", () => {
  withMarkedTree((dir) =>
    assert.equal(
      checkBlitzMarks(dir, 3),
      "contracts/l3/world-native/src has 2 Blitz marks: lower BLITZ_MARKS in contracts/l3/world-native/scripts/check-blitz-marks.mjs to 2",
    ),
  );
});

test("the figure met passes", () => {
  withMarkedTree((dir) => assert.equal(checkBlitzMarks(dir, 2), null));
});

test("the world source holds exactly the allowed marks", () => {
  assert.equal(countBlitzMarks(worldSource), BLITZ_MARKS);
});
