import assert from "node:assert/strict";
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import test from "node:test";
import { rawClockReads, worldSource } from "./check-clock-reads.mjs";

function withTree(files, run) {
  const dir = mkdtempSync(join(tmpdir(), "clock-reads-"));
  try {
    for (const [path, text] of Object.entries(files)) {
      mkdirSync(join(dir, path, ".."), { recursive: true });
      writeFileSync(join(dir, path), text);
    }
    run(dir);
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

test("a raw day unit, tick or relic read outside the clock is refused, naming the accessor", () => {
  withTree(
    {
      "logic/quests.cairo": "let unit = crate::balance::rules::SWITCHES.day_unit_seconds;\n",
      "logic/deep.cairo": "let tick = crate::balance::rules::TICK_CONFIG.armies_tick_in_seconds;\n",
      "logic/relics.cairo": "let seconds = crate::balance::rules::RELIC_SECONDS_PER_RANK;\n",
    },
    (dir) =>
      assert.deepEqual(rawClockReads(dir).sort(), [
        "logic/deep.cairo reads a clock its game may scale outside clock.cairo: use crate::clock::tick_config(game)",
        "logic/quests.cairo reads a clock its game may scale outside clock.cairo: use crate::clock::day_unit_seconds(game)",
        "logic/relics.cairo reads a clock its game may scale outside clock.cairo: use crate::clock::relic_seconds_per_rank(game)",
      ]),
  );
});

test("a production rate changed outside start and stop production is refused", () => {
  withTree({ "logic/structures.cairo": "resource.production.production_rate += rate;\n" }, (dir) =>
    assert.deepEqual(rawClockReads(dir), [
      "logic/structures.cairo reads a clock its game may scale outside logic/resources.cairo: use start_production and stop_production, which scale a rate by the game's clock",
    ]),
  );
});

test("the clock itself, generated balance, tests, the days switch and the delivery tick pass", () => {
  withTree(
    {
      "clock.cairo": "crate::balance::rules::SWITCHES.day_unit_seconds / scale; TICK_CONFIG; RELIC_SECONDS_PER_RANK\n",
      "balance/rules.cairo": "// @generated by scripts/balance-modules.ts\npub const TICK_CONFIG: TickConfig = x;\n",
      "tests/days.cairo": "SWITCHES.day_unit_seconds\n",
      "rules.cairo": "pub const DAYS_IN_PLAY: bool = crate::balance::rules::SWITCHES.day_unit_seconds != 0;\n",
      "logic/lords.cairo": "delivery_tick: crate::balance::rules::TICK_CONFIG.delivery_tick_in_seconds,\n",
    },
    (dir) => assert.deepEqual(rawClockReads(dir), []),
  );
});

test("the world reads every clock through crate::clock", () => {
  assert.deepEqual(rawClockReads(worldSource), []);
});
