// Writes src/email-art.gen.ts: each player email's header art as an inline JPEG, from the game's own art. A painting
// fades to night under the Realms lockup, and the email's title is lettered in Bokor, the game's title face, so every
// client shows it (Gmail and Outlook load no web fonts). Rerun after changing a painting, the lockup or a title:
// pnpm --dir packages/notifications build:email-art
import sharp from "sharp";
import { readFile, writeFile } from "node:fs/promises";

const publicDir = new URL("../../../apps/game/public/", import.meta.url);
const out = new URL("../src/email-art.gen.ts", import.meta.url);

const WIDTH = 1200; // drawn at 600: twice the pixels for sharp phones
const HEIGHT = 640;
const NIGHT = "#130f0c"; // the shell's ground (apps/game/src/tokens.ts)
const LETTERING = "#f3d08a"; // gold2
const LOCKUP = "#f4ebdc"; // cream

/** Each email's painting, where its crop sits (0 top, 1 bottom), and its title. */
const ART = {
  "sign-in-code": { painting: "frontier-mist", focus: 0.55, title: "Your sign-in code" },
  "wallet-changed": { painting: "season-citadel", focus: 0.45, title: "Payout wallet changed" },
  "wallet-unlinked": { painting: "season-citadel", focus: 0.45, title: "Payout wallet unlinked" },
};

const painting = async (name, focus) => {
  const file = new URL(`images/landscapes/${name}-1536.webp`, publicDir);
  const resized = await sharp(await readFile(file))
    .resize({ width: WIDTH })
    .toBuffer({ resolveWithObject: true });
  const top = Math.round((resized.info.height - HEIGHT) * focus);
  return sharp(resized.data).extract({ left: 0, top, width: WIDTH, height: HEIGHT }).toBuffer();
};

/** Night rising from the bottom, and a lighter veil from the top for the lockup. */
const nightfall = () => {
  const stops = (from, strength) =>
    Array.from({ length: 11 }, (_, i) => {
      const t = i / 10;
      const opacity = t < from ? 0 : strength * ((t - from) / (1 - from)) ** 1.6;
      return `<stop offset="${t}" stop-color="${NIGHT}" stop-opacity="${opacity.toFixed(3)}"/>`;
    }).join("");
  return Buffer.from(`<svg xmlns="http://www.w3.org/2000/svg" width="${WIDTH}" height="${HEIGHT}">
<defs><linearGradient id="b" x1="0" y1="0" x2="0" y2="1">${stops(0.3, 1)}</linearGradient>
<linearGradient id="t" x1="0" y1="1" x2="0" y2="0">${stops(0.7, 0.7)}</linearGradient></defs>
<rect width="100%" height="100%" fill="url(#t)"/><rect width="100%" height="100%" fill="url(#b)"/></svg>`);
};

const lockup = async () => {
  const svg = (await readFile(new URL("images/logos/realms-lockup.svg", publicDir), "utf8")).replace(
    'fill="#F4EBDC"',
    `fill="${LOCKUP}"`,
  );
  return sharp(Buffer.from(svg), { density: 300 }).resize({ width: 300 }).png().toBuffer();
};

const lettering = async (title, colour) => {
  const fontfile = new URL("fonts/bokor-regular.ttf", publicDir).pathname;
  return sharp({
    text: { text: `<span foreground="${colour}">${title}</span>`, font: "Bokor 84", fontfile, dpi: 96, rgba: true },
  })
    .png()
    .toBuffer({ resolveWithObject: true });
};

const header = async ({ painting: name, focus, title }, mark) => {
  const gold = await lettering(title, LETTERING);
  const shadow = await sharp((await lettering(title, "#000000")).data)
    .ensureAlpha(0.6)
    .blur(3)
    .toBuffer();
  const left = 72;
  const top = HEIGHT - 48 - gold.info.height;
  return sharp(await painting(name, focus))
    .composite([
      { input: nightfall() },
      { input: mark, left: 72, top: 56 },
      { input: shadow, left: left + 3, top: top + 4 },
      { input: gold.data, left, top },
    ])
    .jpeg({ quality: 68, progressive: true, mozjpeg: true })
    .toBuffer();
};

const mark = await lockup();
const entries = [];
for (const [id, art] of Object.entries(ART)) {
  const jpeg = await header(art, mark);
  entries.push(
    `  /** ${art.painting}, ${Math.round(jpeg.length / 1024)} KB. */\n  "${id}": { title: ${JSON.stringify(art.title)}, jpeg: "${jpeg.toString("base64")}" },`,
  );
}
await writeFile(
  out,
  `// Generated by scripts/build-email-art.mjs from the game's art; rerun it instead of editing this file.

/** Each player email's header: the title lettered on it, and the 1200 x 640 JPEG in base64, sent inline. */
export const EMAIL_ART = {
${entries.join("\n")}
} as const;

export type EmailArt = keyof typeof EMAIL_ART;
`,
);
console.log(`Wrote ${entries.length} email headers to ${out.pathname}`);
